// Превращает ошибку API при создании записи в понятный клиенту текст.
// Текст самого бэкенда клиенту не показываем: он слишком технический
// («мастер в отпуске», «вне окна записи»). Решаем по статусу ответа
// и по названию поля.
//
// Возвращает:
//   general   — общее сообщение;
//   fields    — ошибки для полей {name, phone};
//   resetTime — true, если выбранное время нужно сбросить (занято или
//               запись по этим параметрам невозможна).
export function describeBookingError(error) {
  const status = error?.status

  // Время (или мастер) уже недоступны: например, его только что заняли.
  if (status === 409) {
    return {
      general: 'К сожалению, это время уже занято. Выберите другое.',
      resetTime: true,
    }
  }

  if (status === 429) {
    return {
      general: 'Слишком много попыток. Подождите немного и попробуйте снова.',
    }
  }

  if (status === 400 && error.fields) {
    const fields = {}

    if (error.fields.client_name) fields.name = 'Укажите имя.'
    if (error.fields.client_phone) {
      fields.phone = 'Введите номер в формате 0991234567.'
    }

    if (Object.keys(fields).length > 0) return { fields }

    // Ошибка в дате, времени, мастере или услуге: пусть выберет заново.
    return {
      general:
        'Не удалось оформить запись на выбранное время. Выберите время заново.',
      resetTime: true,
    }
  }

  // Нет связи с сервером или он ответил ошибкой 5xx.
  return {
    general:
      'Не удалось отправить заявку. Проверьте соединение и попробуйте ещё раз.',
  }
}
